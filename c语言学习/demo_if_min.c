/* demo_if_min.c -- if 的最小形态：就问一句话，看答案是"是"还是"不是"
 * 同一个 if 跑了两次：第一次问题是"是"，第二次问题是"不是"。
 * 对比两次输出，就看出 if 到底在干什么了。
 */
#include <stdio.h>

int main(void)
{
    int age = 20;                        /* 盒子里放 20 */

    if (age >= 18)                       /* 问：age 大于等于 18 吗？ */
        printf("A: 成年了\n");           /* 答案"是" -> 这一句执行了 */

    printf("A: 这句在 if 外面，永远打印\n");

    age = 12;                            /* 把盒子里的数换成 12 */

    if (age >= 18)                       /* 同一个问题，再问一次 */
        printf("B: 成年了\n");           /* 答案"不是" -> 这一句被跳过了 */

    printf("B: 这句在 if 外面，永远打印\n");

    return 0;
}
